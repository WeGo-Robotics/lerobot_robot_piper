#!/bin/bash
# install_can_persist.sh — make Piper CAN names survive reboots, hotplugs,
# and USB port swaps.
#
# Why serial-pinned udev rules: can0/can1 are kernel enumeration order. Swap
# two adapters between USB ports (or change boot order) and the two arms swap
# names — saved roles and presets then point at the WRONG arm, so a leader can
# receive follower commands. The adapter's USB serial never changes and the
# adapter stays wired to its arm, so pinning name-to-serial makes the name
# follow the arm no matter which port it is plugged into.
#
# What gets installed:
#   /etc/udev/rules.d/99-piper-can.rules      serial -> NAME= rename at plug
#                                             time + hotplug trigger for the
#                                             bring-up service
#   /usr/local/bin/piper-can-restore          copy of can_restore.sh
#   /etc/systemd/system/piper-can-up.service  oneshot: bitrate + link up
#
# Prerequisite: run `piper-setup` once (writes ~/piper_config.json) with all
# arms plugged in, and keep them plugged in while running this installer —
# serials are read live from sysfs using the USB addresses in the config.
#
# Re-run this installer whenever an arm is rewired to a different adapter or
# `piper-setup` is run again; the rules are regenerated from the new config.
#
# Usage:
#   sudo bash scripts/install_can_persist.sh            # install / refresh
#   sudo bash scripts/install_can_persist.sh uninstall  # remove everything

set -eu

if [ "$(id -u)" -ne 0 ]; then
    echo "Run with sudo: sudo bash scripts/install_can_persist.sh"
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN=/usr/local/bin/piper-can-restore
UNIT=/etc/systemd/system/piper-can-up.service
RULES=/etc/udev/rules.d/99-piper-can.rules

# Config lives in the invoking user's home, but the service runs as root.
REAL_USER="${SUDO_USER:-root}"
REAL_HOME=$(getent passwd "$REAL_USER" | cut -d: -f6)
CONFIG="$REAL_HOME/piper_config.json"

if [ "${1:-}" = "uninstall" ]; then
    systemctl disable --now piper-can-up.service 2>/dev/null || true
    rm -f "$BIN" "$UNIT" "$RULES"
    systemctl daemon-reload
    udevadm control --reload-rules
    echo "Removed."
    exit 0
fi

if [ ! -f "$CONFIG" ]; then
    echo "Error: $CONFIG not found. Run 'piper-setup' first (with the arms plugged in)."
    exit 1
fi

# ── Generate serial-pinned udev rules from the config ────────────────────────
# python3 resolves each arm's bus-info ("1-2:1.0") to its USB device node
# ("1-2") and reads idVendor/idProduct/serial from sysfs.
RULE_BODY=$(python3 - "$CONFIG" <<'EOF'
import json, sys
from pathlib import Path

USB = Path("/sys/bus/usb/devices")

def attr(node, name):
    try:
        return (node / name).read_text().strip()
    except OSError:
        return ""

with open(sys.argv[1]) as f:
    arms = json.load(f).get("arms", [])

resolved = []   # (serial, vid, pid, name, bus)
for arm in arms:
    bus, name = arm.get("bus_info"), arm.get("can_name")
    if not bus or not name:
        continue
    node = USB / bus.split(":")[0]          # "1-2:1.0" -> "1-2"
    vid, pid, serial = attr(node, "idVendor"), attr(node, "idProduct"), attr(node, "serial")
    if not serial:
        print(f"WARNING: no USB serial for {name} (bus {bus}) -- rename for this arm", file=sys.stderr)
        print("falls back to the bring-up service and follows the USB PORT, not the arm.", file=sys.stderr)
        continue
    resolved.append((serial, vid, pid, name, bus))

# A duplicated serial would make two rules match the same device: the first
# arm enumerated wins the name, the other rename silently fails. Refuse.
by_serial = {}
for serial, _, _, name, bus in resolved:
    by_serial.setdefault(serial, []).append(f"{name} (bus {bus})")
dups = {s: names for s, names in by_serial.items() if len(names) > 1}
if dups:
    print("ERROR: adapters with IDENTICAL USB serials detected:", file=sys.stderr)
    for s, names in dups.items():
        print(f"  serial {s}: {', '.join(names)}", file=sys.stderr)
    print("Serial-pinned rules cannot distinguish them. Either reflash the", file=sys.stderr)
    print("adapter serials (candleLight firmware) or skip this installer and", file=sys.stderr)
    print("rely on scripts/can_restore.sh (USB-port-based, no port swapping).", file=sys.stderr)
    sys.exit(1)

for serial, vid, pid, name, _ in resolved:
    print(f'SUBSYSTEM=="net", ACTION=="add", ATTRS{{idVendor}}=="{vid}", '
          f'ATTRS{{idProduct}}=="{pid}", ATTRS{{serial}}=="{serial}", NAME="{name}"')
EOF
)

if [ -z "$RULE_BODY" ]; then
    echo "Error: no rules generated. Are the arms plugged in on the USB ports recorded in $CONFIG?"
    exit 1
fi

cat > "$RULES" <<EOF
# Piper CAN adapter name pinning — generated by install_can_persist.sh
# from $CONFIG. Do not edit by hand; re-run the installer instead.
#
# Names follow the ADAPTER (its USB serial), and the adapter follows the arm
# it is wired to — not the USB port. If an arm is rewired to a different
# adapter, re-run piper-setup and this installer, or the names will lie.
# Names must start with "can" to show up in \`ip link show type can\`.

$RULE_BODY

# Any gs_usb CAN device appearing pulls the bring-up service (bitrate + up).
SUBSYSTEM=="net", ACTION=="add", ENV{ID_USB_DRIVER}=="gs_usb", TAG+="systemd", ENV{SYSTEMD_WANTS}+="piper-can-up.service"
EOF

# ── Bring-up service (bitrate + link up; also rename fallback) ───────────────
install -m 755 "$SCRIPT_DIR/can_restore.sh" "$BIN"

cat > "$UNIT" <<EOF
[Unit]
Description=Bring up Piper CAN interfaces (bitrate + link up)
After=network-pre.target

[Service]
Type=oneshot
Environment=PIPER_CONFIG=$CONFIG
ExecStart=$BIN

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable piper-can-up.service
udevadm control --reload-rules

echo
echo "Installed. Generated rules:"
grep -v '^#' "$RULES" | grep -v '^$' | sed 's/^/  /'
echo
echo "The NAME= rename applies when an adapter is (re)plugged or at boot —"
echo "replug the adapters or reboot once now. Test the bring-up with:"
echo "  sudo systemctl start piper-can-up && ip -br link show type can"
